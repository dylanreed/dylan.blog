// ABOUTME: Renders docs/BRAND-BOOK.md from brand/tokens.json so the book can never drift from the tokens.
// ABOUTME: Run with `npm run brandbook`. Edit brand/tokens.json, never the generated markdown.

const fs = require('node:fs');
const path = require('node:path');

const TOKENS_PATH = path.resolve(__dirname, '..', 'brand', 'tokens.json');
const OUTPUT_PATH = path.resolve(__dirname, '..', 'docs', 'BRAND-BOOK.md');

function loadTokens(file = TOKENS_PATH) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

const STATUS_LABEL = {
  base: 'base — every other mode overrides this',
  built: 'built',
  variables: 'variables — CSS custom properties',
  stub: 'stub — art shipped, theme unwritten',
};

function fontsOf(mode) {
  const t = mode.type || {};
  const names = [t.display, t.body, t.accent, t.ui].filter(Boolean);
  return names.length ? names.join(', ') : '—';
}

function swatches(mode) {
  const p = mode.palette || {};
  const hexes = Object.values(p).filter(v => /^#[0-9a-fA-F]{3,8}$/.test(v));
  return hexes.length ? hexes.map(h => `\`${h}\``).join(' ') : '—';
}

function modeTable(tokens) {
  const rows = Object.entries(tokens.modes)
    .sort((a, b) => (b[1].cssRules || 0) - (a[1].cssRules || 0))
    .map(([name, m]) =>
      `| \`${name}\` | ${STATUS_LABEL[m.status] || m.status} | ${m.cssRules} | ${fontsOf(m)} | ${swatches(m)} |`);
  return [
    '| Mode | Status | CSS rules | Type | Palette |',
    '|---|---|---:|---|---|',
    ...rows,
  ].join('\n');
}

function categoryTable(tokens) {
  const rows = Object.entries(tokens.categories).map(([name, c]) =>
    `| \`${name}\` | \`${c.glow}\` | \`${c.header}\` | \`${c.sprite}\` | ${c.use} |`);
  return [
    '| Category | Glow | Header | Sprite | Use for |',
    '|---|---|---|---|---|',
    ...rows,
  ].join('\n');
}

function socialTable(tokens) {
  const rows = Object.entries(tokens.social).map(([name, s]) =>
    `| \`${name}\` | ${s.width}×${s.height} | \`${s.template}\` | ${s.use} |`);
  return [
    '| Surface | Size | Template | Use |',
    '|---|---|---|---|',
    ...rows,
  ].join('\n');
}

function shelfTagList(tokens) {
  return Object.entries(tokens.reviewCard.shelfTags)
    .filter(([k]) => !k.startsWith('$'))
    .map(([tag, meaning]) => `- \`${tag.toUpperCase()}\` — ${meaning}`)
    .join('\n');
}

function orphanList(tokens) {
  return Object.entries(tokens.orphanedArt)
    .filter(([k]) => !k.startsWith('$'))
    .map(([file, why]) => `- \`${file}\` — ${why}`)
    .join('\n');
}

function renderBrandBook(tokens) {
  const id = tokens.identity;
  const bar = tokens.reviewCard.enjoymentBar;
  const stubs = Object.entries(tokens.modes).filter(([, m]) => m.status === 'stub').map(([n]) => `\`${n}\``);

  return `<!-- GENERATED FILE — do not edit by hand. -->
<!-- Source: brand/tokens.json · Regenerate: npm run brandbook -->

# ${id.name} — Brand Book

> ${id.premise}

Hosted on ${id.host}. The theme lives at \`${id.themeRepo}\`.

This document is **generated** from \`brand/tokens.json\`. If something here is wrong, fix the tokens and re-run \`npm run brandbook\` — do not edit this file.

---

## Type

The blog does not have one typeface, and that is deliberate: **each mode carries its own typographic personality.** The base supplies the fallback everything else inherits.

- **Display:** ${tokens.type.base.display}
- **Body:** ${tokens.type.base.body}
- **Wordmark:** ${tokens.type.base.wordmark} — set as "${id.wordmark}"

${tokens.type.rendering.$note}

---

## Modes

${modeTable(tokens)}

${stubs.length ? `**${stubs.join(' and ')} are stubs.** They ship complete art directories against two CSS rules each. Either finish them or retire the art — right now they are neither.` : ''}

---

## Categories

The category drives the header art, the sprite and the accent glow on every share image. This table is the **only** category list; anything disagreeing with it is wrong.

${categoryTable(tokens)}

### Orphaned art

${orphanList(tokens)}

---

## Social surfaces

${socialTable(tokens)}

---

## The book review card

Book reviews come in two depths — a **shelf talker** (250–400 words) and a **full review** (800–1200) — and both carry the same card.

### Enjoyment bar

A **${bar.variant}** bar, not a count of icons: it fills whatever width it is given, so one treatment serves the square card, the story frame and the in-post embed.

- Fill \`${bar.fill}\` on well \`${bar.well}\`, trough \`${bar.trough}\`
- ${bar.stripeAngle}° stripes on a ${bar.tileSize}px tile
- Animated: \`${bar.animation.name}\` ${bar.animation.duration} ${bar.animation.timing}. ${bar.animation.note}

**Never print a percentage on the enjoyment bar.** ${bar.numberNote}

Label states:

- **complete** → \`${bar.labelStates.complete}\`
- **DNF** → \`${bar.labelStates.dnf}\`
- otherwise → nothing

### Shelf tags

${tokens.reviewCard.shelfTags.$note}

${shelfTagList(tokens)}
`;
}

function main() {
  const tokens = loadTokens();
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, renderBrandBook(tokens));
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT_PATH)}`);
}

if (require.main === module) main();

module.exports = { loadTokens, renderBrandBook, modeTable, categoryTable, socialTable };
